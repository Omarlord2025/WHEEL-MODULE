import frappe
from frappe.tests.utils import FrappeTestCase

from wheel_tracker.wheel_tracker.doctype.wheel.wheel import (
	assign_to_job_card,
	reinstate_wheel,
	release_from_job_card,
	retire_wheel,
)
from wheel_tracker.test_helpers import (
	cleanup_wheel_tracker_records,
	make_job_card,
	make_measurement_event,
	make_wheel,
	make_wheel_type,
)


class TestWheel(FrappeTestCase):
	def setUp(self):
		self._created = []
		self.wheel_type = self.track_type(make_wheel_type(original_diameter=100, original_inner_diameter=60, original_diamond_height=6))

	def tearDown(self):
		cleanup_wheel_tracker_records(self._created)

	def track_type(self, doc):
		self._created.append(doc.name)
		return doc

	def test_factory_wheel_code_autogenerated_when_blank(self):
		wheel = make_wheel(self.wheel_type.name)
		self.assertTrue(wheel.name.startswith("SH-D-1A1-100-T6-"))
		self.assertEqual(wheel.factory_wheel_code, wheel.name)

	def test_manual_factory_wheel_code_is_respected(self):
		wheel = make_wheel(self.wheel_type.name, factory_wheel_code="MY-CUSTOM-CODE-001")
		self.assertEqual(wheel.name, "MY-CUSTOM-CODE-001")

	def test_new_wheel_has_zero_consumption(self):
		wheel = make_wheel(self.wheel_type.name)
		self.assertAlmostEqual(wheel.consumption_percent, 0, places=3)

	def test_wear_calc_matches_wheel_type_baseline(self):
		wheel = make_wheel(self.wheel_type.name)
		half_volume = self.wheel_type.original_volume / 2
		wheel.current_volume = half_volume
		wheel.save()
		self.assertAlmostEqual(wheel.usable_current_volume, half_volume * 0.9, places=2)
		self.assertAlmostEqual(wheel.consumption_percent, 50, places=1)

	def test_wear_calc_uses_wheel_type_floor_override(self):
		override_type = self.track_type(
			make_wheel_type(
				original_diameter=100,
				original_inner_diameter=60,
				original_diamond_height=6,
				usable_volume_floor_percent=25,
			)
		)
		wheel = make_wheel(override_type.name)
		half_volume = override_type.original_volume / 2
		wheel.current_volume = half_volume
		wheel.save()
		self.assertAlmostEqual(wheel.usable_current_volume, half_volume * 0.75, places=2)

	def test_auto_retires_at_full_consumption(self):
		wheel = make_wheel(self.wheel_type.name)
		wheel.current_volume = 0
		wheel.save()
		self.assertEqual(wheel.status, "Retired")
		self.assertTrue(wheel.retirement_date)
		self.assertIn("Auto-retired", wheel.retirement_reason)

	def test_assign_to_job_card_requires_in_stock(self):
		wheel = make_wheel(self.wheel_type.name, status="Retired")
		self.assertRaises(frappe.ValidationError, assign_to_job_card, wheel.name, "JC-FAKE")

	def test_assign_and_release_round_trip(self):
		wheel = make_wheel(self.wheel_type.name)
		job_card = make_job_card()

		status = assign_to_job_card(wheel.name, job_card.name)
		self.assertEqual(status, "In Use")
		wheel.reload()
		self.assertEqual(wheel.current_job_card, job_card.name)

		status = release_from_job_card(wheel.name)
		self.assertEqual(status, "In Stock")
		wheel.reload()
		self.assertFalse(wheel.current_job_card)

	def test_release_requires_in_use(self):
		wheel = make_wheel(self.wheel_type.name)
		self.assertRaises(frappe.ValidationError, release_from_job_card, wheel.name)

	def test_total_cost_allocated_rolls_up_from_measurement_events(self):
		wheel = make_wheel(self.wheel_type.name)
		first = make_measurement_event(wheel.name, diameter=95)
		wheel.reload()
		self.assertAlmostEqual(wheel.total_cost_allocated, first.job_cost, places=4)

		second = make_measurement_event(wheel.name, diameter=85)
		wheel.reload()
		self.assertAlmostEqual(wheel.total_cost_allocated, first.job_cost + second.job_cost, places=4)

	def test_retire_wheel_sets_status_and_reason(self):
		wheel = make_wheel(self.wheel_type.name)
		status = retire_wheel(wheel.name, "Chipped during use")
		self.assertEqual(status, "Retired")
		wheel.reload()
		self.assertEqual(wheel.status, "Retired")
		self.assertEqual(wheel.retirement_reason, "Chipped during use")
		self.assertTrue(wheel.retirement_date)

	def test_retire_wheel_clears_current_job_card(self):
		wheel = make_wheel(self.wheel_type.name)
		job_card = make_job_card()
		assign_to_job_card(wheel.name, job_card.name)

		retire_wheel(wheel.name, "Cracked")
		wheel.reload()
		self.assertEqual(wheel.status, "Retired")
		self.assertFalse(wheel.current_job_card)

	def test_retire_wheel_is_a_noop_if_already_retired(self):
		wheel = make_wheel(self.wheel_type.name)
		retire_wheel(wheel.name, "First reason")
		retire_wheel(wheel.name, "Second reason")
		wheel.reload()
		self.assertEqual(wheel.retirement_reason, "First reason")

	def test_reinstate_wheel_returns_to_in_stock(self):
		wheel = make_wheel(self.wheel_type.name)
		retire_wheel(wheel.name, "Marked not usable by mistake")

		status = reinstate_wheel(wheel.name)
		self.assertEqual(status, "In Stock")
		wheel.reload()
		self.assertEqual(wheel.status, "In Stock")
		self.assertFalse(wheel.retirement_date)
		self.assertFalse(wheel.retirement_reason)

	def test_reinstate_wheel_is_a_noop_if_not_retired(self):
		wheel = make_wheel(self.wheel_type.name)
		status = reinstate_wheel(wheel.name)
		self.assertEqual(status, "In Stock")
